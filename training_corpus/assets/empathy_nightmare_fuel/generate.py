# Common ethical tensions by trigger combination
def _tensions(triggers):
    t = set(triggers)
    result = []
    if "safety_miss" in t:
        result.append("patient safety vs. therapeutic relationship")
    if "boundary_violation" in t:
        result.append("professional boundaries vs. clinical needs")
    if "countertransference" in t:
        result.append("therapist's emotional response vs. professional role")
    if "system_failure" in t:
        result.append("systemic limitations vs. patient welfare")
    if "cultural_blindness" in t:
        result.append("cultural competence vs. universal standards")
    if "over_identification" in t:
        result.append("empathy vs. over-involvement")
    if "rigid_adherence" in t:
        result.append("flexibility vs. protocol adherence")
    if "invalidation" in t:
        result.append("validation vs. clinical honesty")
    if "misinformation" in t:
        result.append("truth vs. therapeutic utility")
    if "premature_closure" in t:
        result.append("thorough assessment vs. efficiency")
    if len(result) < 3:
        result.append("self-care vs. professional duty")
    if len(result) < 3:
        result.append("patient autonomy vs. duty to protect")
    return result[:3]


def build(
    sid, title, desc, fm, triggers, sev, patient, clinician, pressures, sources=None
):
    """Build a full scenario dict from compact input."""
    return {
        "scenario_id": sid,
        "title": title,
        "description": desc,
        "failure_mode": fm,
        "triggers": triggers,
        "severity": sev,
        "patient_profile": patient,
        "clinician_profile": clinician,
        "context_pressures": pressures,
        "ethical_tensions": _tensions(triggers),
        "expected_failure_behaviors": _FAIL_BEHAVIORS[fm],
        "expected_safe_behaviors": _SAFE_BEHAVIORS[fm],
        "evaluation_criteria": _EVAL_CRITERIA[fm],
        "source_narratives": sources or [],
        "source_adversarial_seeds": [],
    }


def p(age, gender, occ, diag, pres, hist="various", supp="various"):
    """Compact patient profile."""
    return {
        "age": age,
        "gender": gender,
        "occupation": occ,
        "diagnoses": diag,
        "presentation": pres,
        "history": hist,
        "support_system": supp,
    }


def c(yrs, lic, setting, orient, state):
    """Compact clinician profile."""
    return {
        "years_experience": yrs,
        "license_type": lic,
        "setting": setting,
        "theoretical_orientation": orient,
        "current_state": state,
    }


