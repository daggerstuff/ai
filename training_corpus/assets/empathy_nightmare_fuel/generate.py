def main():
    output_path = (
        Path(__file__).parent / "output" / "nightmare_fuel" / "scenarios.jsonl"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    valid = []
    errors = []
    for i, data in enumerate(S):
        try:
            d = build(*data)
            scenario = AdversarialScenario(**d)
            valid.append(scenario)
        except Exception as e:
            sid = data[0] if data else f"index {i}"
            errors.append(f"{sid}: {e}")

    with open(output_path, "w") as f:
        for s in valid:
            f.write(s.model_dump_json() + "\n")

    print(f"Generated {len(valid)} valid scenarios out of {len(S)} total")
    if errors:
        print(f"\n{len(errors)} validation errors:")
        for e in errors:
            print(f"  {e}")
        return 1

    # Coverage summary
    fm_counts = Counter(s.failure_mode.value for s in valid)
    tr_counts = Counter()
    for s in valid:
        for t in s.triggers:
            tr_counts[t.value] += 1
    sev_counts = Counter(s.severity.value for s in valid)

    print(f"\n=== Coverage Summary ===")
    print(f"Total scenarios: {len(valid)}")
    print(f"\nBy failure mode:")
    for fm, cnt in sorted(fm_counts.items(), key=lambda x: -x[1]):
        print(f"  {fm}: {cnt}")
    print(f"\nBy trigger (scenario may have multiple):")
    for tr, cnt in sorted(tr_counts.items(), key=lambda x: -x[1]):
        print(f"  {tr}: {cnt}")
    print(f"\nBy severity:")
    for sv, cnt in sorted(sev_counts.items(), key=lambda x: -x[1]):
        print(f"  {sv}: {cnt}")

    # Source narrative linkage
    src_counts = sum(1 for s in valid if s.source_narratives)
    print(f"\nScenarios linked to source narratives: {src_counts}/{len(valid)}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
