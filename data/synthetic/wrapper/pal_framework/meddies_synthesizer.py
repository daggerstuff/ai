def run(
    out_dir: Path,
    n_records: int,
    seed: int = 7,
    hf_split: str = "train",
    llm_client: LlmCallable | None = None,
) -> dict[str, int]:
    """Fetch n_records from Meddies HF dataset, adapt, synthesize, write JSONLs.

    When ``llm_client`` is provided (anything implementing
    ``__call__(prompt: str, system_prompt: str | None = None) -> str``), the
    three synthesis calls (dialogue / chosen / rejected) route through it
    instead of the deterministic rule-based templates. Empty or falsy LLM
    return values fall back to the rule-based generators so a single failed
    call cannot corrupt the entire batch.
    """
    from datasets import load_dataset  # noqa: PLC0415

    rng = random.Random(seed)
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Load N records from HF (use slice — non-streaming is much faster than
    #    streaming for parquet datasets because it avoids per-row HTTP range reads).
    slice_spec = f"{hf_split}[:{n_records}]"
    ds = load_dataset("Meddies/meddies-persona-vie", split=slice_spec)
    adapted_records: list[dict[str, Any]] = []
    for raw in ds:
        adapted_records.append(adapt_record(dict(raw)))

    # 2. Phase 1: format persona strings
    pal_phase1_path = out_dir / "pal_persona_strings.jsonl"
    with pal_phase1_path.open("w", encoding="utf-8") as f:
        for r in adapted_records:
            f.write(_dumps({"persona_string": format_persona(r)}) + "\n")

    # 3. Build generator inputs (LLM-driven when llm_client provided)
    dialogue_fn, chosen_fn, rejected_fn = _make_synthesizers(llm_client)
    mode_label = "llm" if llm_client is not None else "rule-based"

    selection_path = out_dir / "input_phase_2_1_selection.jsonl"
    with selection_path.open("w", encoding="utf-8") as f:
        for rec in build_selection_input(adapted_records, rng, dialogue_fn=dialogue_fn):
            f.write(_dumps(rec) + "\n")

    dialogue_path = out_dir / "input_phase_2_2_dialogue.jsonl"
    with dialogue_path.open("w", encoding="utf-8") as f:
        for rec in build_dialogue_input(adapted_records, rng, chosen_fn=chosen_fn, dialogue_fn=dialogue_fn):
            f.write(_dumps(rec) + "\n")

    dpo_path = out_dir / "input_phase_3_1_dpo.jsonl"
    with dpo_path.open("w", encoding="utf-8") as f:
        for rec in build_dpo_input(
            adapted_records,
            rng,
            chosen_fn=chosen_fn,
            rejected_fn=rejected_fn,
            dialogue_fn=dialogue_fn,
        ):
            f.write(_dumps(rec) + "\n")

    return {
        "adapted": len(adapted_records),
        "mode": mode_label,
        "pal_phase1": pal_phase1_path.stat().st_size,
        "phase_2_1_input": selection_path.stat().st_size,
        "phase_2_2_input": dialogue_path.stat().st_size,
        "phase_3_1_input": dpo_path.stat().st_size,
    }


def _build_llm_client_from_env(model: str | None = None) -> LlmCallable | None:
    """Construct the repo's ``LLMClient`` against NIM using env vars.

    Honors ``NVIDIA_API_KEY`` / ``LLM_API_KEY`` / ``OPENAI_API_KEY``. Prefers
    the NVIDIA NIM base URL (``https://integrate.api.nvidia.com/v1``) unless
    ``LLM_BASE_URL`` is already set. Returns ``None`` when no key is present
    so the caller can fall back to rule-based generation.
    """
    api_key = os.environ.get("NVIDIA_API_KEY") or os.environ.get("LLM_API_KEY") or os.environ.get("OPENAI_API_KEY")
    if not api_key:
        logger.warning("No NVIDIA_API_KEY / LLM_API_KEY found — falling back to rule-based synthesis.")
        return None

    # Bridge env so OpenAIDriver (which reads LLM_API_KEY/LLM_BASE_URL/LLM_MODEL)
    # lands on the NVIDIA NIM endpoint.
    os.environ.setdefault("LLM_API_KEY", api_key)
    os.environ.setdefault("LLM_BASE_URL", "https://integrate.api.nvidia.com/v1")
    if model:
        os.environ["LLM_MODEL"] = model
    else:
        os.environ.setdefault("LLM_MODEL", "openai/gpt-oss-120b")

    try:
        from ai.utils.common.llm_client import LLMClient  # noqa: PLC0415
    except ImportError:
        # Synthesizer is invoked with PYTHONPATH=training_corpus/pal_framework.
        # Add the repo root so the import resolves.
        repo_root = str(Path(__file__).resolve().parents[3])
        sys.path.insert(0, repo_root)
        from ai.utils.common.llm_client import LLMClient  # type: ignore[import-not-found]  # noqa: PLC0415

    client = LLMClient(driver="nvidia")
    logger.info(
        "LLMClient (driver=nvidia, model=%s, base_url=%s) wired for synthesis",
        getattr(client.driver, "model", "unknown"),
        getattr(client.driver, "base_url", "unknown"),
    )
    return client


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Synthesize PAL generator inputs from Meddies/meddies-persona-vie.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("data/prepared/pal_inputs"),
        help="Directory to write synthesized input JSONL files.",
    )
    parser.add_argument(
        "--n-records",
        type=int,
        default=100,
        help="Number of Meddies records to stream and adapt.",
    )
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--hf-split", type=str, default="train")
    parser.add_argument(
        "--llm",
        action="store_true",
        help=(
            "Use NVIDIA NIM LLM (openai/gpt-oss-120b by default) to generate"
            " dialogue / chosen / rejected text. Falls back to rule-based if no"
            " API key is present."
        ),
    )
    parser.add_argument(
        "--llm-model",
        type=str,
        default=None,
        help="Override the NIM model id (e.g. 'z-ai/glm-5.1'). Implies --llm.",
    )
    args = parser.parse_args(argv)

    llm_client: LlmCallable | None = None
    if args.llm or args.llm_model:
        llm_client = _build_llm_client_from_env(model=args.llm_model)

    report = run(
        args.out_dir,
        args.n_records,
        seed=args.seed,
        hf_split=args.hf_split,
        llm_client=llm_client,
    )
    for _k, _v in report.items():
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
